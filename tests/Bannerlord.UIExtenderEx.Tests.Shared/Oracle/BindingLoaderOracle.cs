    /// <summary>Traverses matching ViewModel instances across all three graphs in lockstep, yielding their hierarchical paths.</summary>
    private static IEnumerable<(string Path, ViewModel?[] Instances)> ViewModelsOf(Run3 run)
    {
        var pending = new Queue<(string, ViewModel?[])>();
        pending.Enqueue(("Root", run.ViewModels.Cast<ViewModel?>().ToArray()));
        var visited = new HashSet<ViewModel>();
        while (pending.Count > 0)
        {
            var (path, instances) = pending.Dequeue();
            if (instances[0] is not { } first || !visited.Add(first))
                continue;
            yield return (path, instances);

            foreach (var property in BoundProperties(first.GetType()))
            {
                if (typeof(ViewModel).IsAssignableFrom(property.PropertyType))
                {
                    pending.Enqueue(($"{path}\\{property.Name}", instances.Select(x => x is null ? null : (ViewModel?) property.GetValue(x)).ToArray()));
                }
                else if (typeof(IMBBindingList).IsAssignableFrom(property.PropertyType))
                {
                    var lists = instances.Select(x => x is null ? null : property.GetValue(x) as IList).ToArray();
                    var count = lists.Min(x => x?.Count ?? 0);
                    for (var i = 0; i < count; i++)
                        pending.Enqueue(($"{path}\\{property.Name}\\{i}", lists.Select(x => x![i] as ViewModel).ToArray()));
                }
            }
        }
    }

    private static readonly System.Collections.Concurrent.ConcurrentDictionary<Type, PropertyInfo[]> BoundPropertiesOf = new();

    /// <summary>Discovers and caches properties decorated with <see cref="DataSourceProperty"/> on the specified type.</summary>
    private static PropertyInfo[] BoundProperties(Type type) => BoundPropertiesOf.GetOrAdd(type, x =>
        [.. x.GetProperties(BindingFlags.Instance | BindingFlags.Public).Where(p => p.IsDefined(typeof(DataSourceProperty)) && p.GetSetMethod() is not null)]);

    private static readonly System.Collections.Concurrent.ConcurrentDictionary<PropertyInfo, Type> ValueTypes = new();

    private static Type ValueTypeOf(PropertyInfo property) => ValueTypes.GetOrAdd(property, SynthValues.ValueTypeOf);

    private static int SeedOf(ViewModel viewModel) => (int) viewModel.GetType().GetField("Seed")!.GetValue(viewModel)!;

    private static bool IsScalar(PropertyInfo property) =>
        !typeof(ViewModel).IsAssignableFrom(property.PropertyType) && !typeof(IMBBindingList).IsAssignableFrom(property.PropertyType);

    private void ChangeProperties(Run3 run)
    {
        for (var round = 1; round <= 2; round++)
        {
            var changed = 0;
            foreach (var (path, instances) in ViewModelsOf(run).ToList())
            {
                var scalars = BoundProperties(instances[0]!.GetType()).Where(IsScalar).ToList();
                if (scalars.Count == 0)
                    continue;
                var seed = SeedOf(instances[0]!);
                foreach (var property in scalars)
                {
                    var value = SynthValues.Get(ValueTypeOf(property), seed, property.Name, round);
                    ApplyToAll(run, $"round {round}: {path}.{property.Name}", side => property.SetValue(instances[side], value));
                }
                if (changed++ < MaxDetailedChecks)
                    Check(run, $"round {round}: {path}");
            }
            Check(run, $"round {round}", deep: true);
        }
    }

    private void ReplaceChildren(Run3 run)
    {
        var seed = 1000;
        var replaced = 0;
        // Captures pre-replacement state to distinguish stale XML views from unintended deviations.
        var phaseBefore = Shallow(run);
        LogMemory("children: after the phase's shallow snapshots");
        // Chains baseline states sequentially across initial detailed replacement steps.
        var before = phaseBefore;
        // Reuses post-replacement widget identities as pre-replacement baselines for subsequent steps.
        Dictionary<string, (Widget Widget, object? ViewModel)>[]? widgetsBefore = null;
        foreach (var (path, instances) in ViewModelsOf(run).ToList())
        {
            foreach (var property in BoundProperties(instances[0]!.GetType()).Where(x => typeof(ViewModel).IsAssignableFrom(x.PropertyType)))
            {
                var childSeed = seed++;
                var detailed = replaced++ < MaxDetailedChecks;
                widgetsBefore ??= run.Timed("identities", () => Identities(run));
                ApplyToAll(run, $"replacing {path}\\{property.Name}", side => property.SetValue(instances[side],
                    Activator.CreateInstance(property.PropertyType, run.Logs[side], $"{path}\\{property.Name}", childSeed)));
                var widgetsAfter = run.Timed("identities", () => Identities(run));
                if (run.Timed("rebuilt", () => RebuiltInXml(widgetsBefore, widgetsAfter)) is { Count: > 0 } rebuilt)
                {
                    run.Diverged.AddRange(rebuilt);
                    run.RebuiltSinceCheck.AddRange(rebuilt);
                    run.IntendedSinceCheck = true;
                }
                widgetsBefore = widgetsAfter;
                if (detailed)
                {
                    before = Check(run, $"replacing {path}\\{property.Name}", replacingBefore: before, keepShallow: replaced < MaxDetailedChecks)!;
                    widgetsBefore = null;
                    if (replaced == 1)
                        LogMemory("children: after the first replacement's check, which keeps its shallow snapshots");
                }
            }
        }
        Check(run, "replacing child ViewModels", deep: true, replacingBefore: phaseBefore);
    }

    /// <summary>
    /// Releases movie instances and verifies that event handlers detach cleanly without leaving lingering subscriptions.
    /// </summary>
    private void Release(Run3 run)
    {
        run.Timed("of which releasing", () => ApplyToAll(run, "releasing the movie", side => run.Movies[side]!.Release()));
        Check(run, "releasing the movie", trees: false);

        var handlers = new Dictionary<string, int>[3];
        for (var side = 0; side < 3; side++)
            handlers[side] = run.Timed("handlers", () => HandlersOf(ViewModelsOf(run).Select(x => (x.Path, x.Instances[side]))));
        foreach (var key in handlers[0].Keys.Union(handlers[1].Keys).OrderBy(x => x, StringComparer.Ordinal))
        {
            var xml = handlers[0].TryGetValue(key, out var x) ? x : 0;
            var compiled = handlers[1].TryGetValue(key, out var c) ? c : 0;
            var control = handlers[2].TryGetValue(key, out var k) ? k : 0;
            if (xml == control && xml != compiled)
                Record(run, $"after release: {key}: XML {xml} handlers, compiled {compiled}");
        }

        foreach (var (path, instances) in ViewModelsOf(run).ToList())
        {
            var seed = SeedOf(instances[0]!);
            foreach (var property in BoundProperties(instances[0]!.GetType()).Where(IsScalar))
            {
                var value = SynthValues.Get(ValueTypeOf(property), seed, property.Name, 3);
                ApplyToAll(run, $"after release: {path}.{property.Name}", side => property.SetValue(instances[side], value));
            }
        }
        Check(run, "changing the ViewModels after release", trees: false);
    }

    /// <summary>Determines whether a ViewModel invocation represents an engine property reset upon widget disconnection.</summary>
    private static bool IsResetWrittenBack(Run3 run, string entry)
    {
        var equals = entry.IndexOf(" = ", StringComparison.Ordinal);
        if (equals < 0)
            return false;
        var target = entry.Substring(0, equals);
        var name = target.Substring(target.LastIndexOf('.') + 1);
        return run.ResetOnRemoval.TryGetValue(name, out var values) && values.Contains(entry.Substring(equals + 3));
    }

    /// <summary>Counts active event handler delegates across all ViewModels and binding lists in the hierarchy.</summary>
    public static Dictionary<string, int> HandlersOf(IEnumerable<(string Path, ViewModel? ViewModel)> viewModels)
    {
        var counts = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var (path, viewModel) in viewModels)
        {
            if (viewModel is null)
                continue;
            AddHandlers(counts, path, viewModel);
            foreach (var list in BoundProperties(viewModel.GetType()).Where(x => typeof(IMBBindingList).IsAssignableFrom(x.PropertyType)))
            {
                if (list.GetValue(viewModel) is { } value)
                    AddHandlers(counts, $"{path}\\{list.Name}", value);
            }
        }
        return counts;
    }

    private static void AddHandlers(Dictionary<string, int> counts, string path, object target)
    {
        for (var type = target.GetType(); type is not null && type != typeof(object); type = type.BaseType)
        {
            // Inspects event delegates and handler collections, such as MBBindingList.ListChanged.
            foreach (var field in type.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly)
                         .Where(x => typeof(Delegate).IsAssignableFrom(x.FieldType) || IsDelegateList(x.FieldType)))
            {
                var handlers = field.GetValue(target) switch
                {
                    Delegate single => single.GetInvocationList().Length,
                    ICollection list => list.Count,
                    _ => 0,
                };
                if (handlers > 0)
                    counts[$"{path}.{field.Name}"] = handlers;
            }
        }
    }

    private static bool IsDelegateList(Type type) =>
        typeof(ICollection).IsAssignableFrom(type) && type.IsGenericType && type.GetGenericArguments() is { Length: 1 } items && typeof(Delegate).IsAssignableFrom(items[0]);

    private const int MaxDetailedLists = 3;

    private void ChangeLists(Run3 run)
    {
        var seed = 2000;
        var lists = 0;
        foreach (var (path, instances) in ViewModelsOf(run).ToList())
        {
            foreach (var property in BoundProperties(instances[0]!.GetType()).Where(x => typeof(IMBBindingList).IsAssignableFrom(x.PropertyType)))
            {
                var itemType = property.PropertyType.GetGenericArguments()[0];
                var listPath = $"{path}\\{property.Name}";
                IList ListOf(int side) => (IList) property.GetValue(instances[side])!;
                object NewItem(int side, int itemSeed) => Activator.CreateInstance(itemType, run.Logs[side], $"{listPath}\\new{itemSeed}", itemSeed)!;

                // Executes detailed checks on initial lists, batching subsequent list checks for efficiency.
                var detailed = lists++ < MaxDetailedLists;
                void CheckIfDetailed(string step)
                {
                    if (detailed)
                        Check(run, $"{listPath}: {step}");
                }

                var added = seed++;
                ApplyToAll(run, $"{listPath}: add", side => ListOf(side).Add(NewItem(side, added)));
                MarkStaleIndexed(run);
                CheckIfDetailed("add");
                var inserted = seed++;
                ApplyToAll(run, $"{listPath}: insert at 0", side => ListOf(side).Insert(0, NewItem(side, inserted)));
                MarkStaleIndexed(run);
                CheckIfDetailed("insert at 0");
                ApplyToAll(run, $"{listPath}: remove at 0", side => ListOf(side).RemoveAt(0));
                MarkStaleIndexed(run);
                CheckIfDetailed("remove at 0");
                ApplyToAll(run, $"{listPath}: clear", side => ListOf(side).Clear());
                MarkStaleIndexed(run);
                CheckIfDetailed("clear");
                var refilled = seed++;
                ApplyToAll(run, $"{listPath}: add after clear", side => ListOf(side).Add(NewItem(side, refilled)));
                MarkStaleIndexed(run);
                if (!detailed)
                    Check(run, $"{listPath}: add, insert, remove, clear, add");
                else
                    CheckIfDetailed("add after clear");
            }
        }
    }

    private static readonly MethodInfo EventFired = typeof(Widget).GetMethod("EventFired", BindingFlags.Instance | BindingFlags.NonPublic)
        ?? throw new InvalidOperationException("Widget.EventFired is gone.");

    /// <summary>
    /// Triggers widget command events across all paired widgets with varying parameter sets, verifying execution parity.
    /// </summary>
    private void FireCommands(Run3 run, HashSet<string> eventNames)
    {
        if (eventNames.Count == 0)
            return;
        var trees = run.Movies.Select(x => x?.RootWidget).ToArray();
        if (trees.Any(x => x is null))
            return;
        foreach (var (path, widgets) in PairedWidgets(trees!))
        {
            // Invokes commands only when at least one variant attaches event listeners.
            if (!widgets.Any(HasEventListeners))
                continue;
            foreach (var eventName in eventNames.OrderBy(x => x, StringComparer.Ordinal))
            {
                foreach (var (argumentsLabel, arguments) in new (string, Func<Widget, object[]>)[] { ("()", _ => []), ("(widget)", w => [w]), ("(\"7\")", _ => ["7"]) })
                    ApplyToAll(run, $"{path} {eventName}{argumentsLabel}", side => EventFired.Invoke(widgets[side], [eventName, arguments(widgets[side])]));
            }
        }
        Check(run, "firing commands", deep: true);
    }

    private static readonly FieldInfo? EventFireField = typeof(Widget).GetField("EventFire", BindingFlags.Instance | BindingFlags.NonPublic);

    private static bool HasEventListeners(Widget widget) => EventFireField is null || EventFireField.GetValue(widget) is not null;

    private static IEnumerable<(string Path, Widget[] Widgets)> PairedWidgets(Widget[] roots)
    {
        var pending = new Stack<(string, Widget[])>();
        pending.Push(("root", roots));
        while (pending.Count > 0)
        {
            var (path, widgets) = pending.Pop();
            yield return (path, widgets);
            var count = widgets[0].ChildCount;
            if (widgets.Any(x => x.ChildCount != count))
                continue;
            for (var i = count - 1; i >= 0; i--)
                pending.Push(($"{path}[{i}]", widgets.Select(x => x.GetChild(i)).ToArray()));
        }
    }
