/// <summary>
/// Executes databinding verification for prefabs by synthesizing dynamic ViewModels and driving runtime movie instances.
/// <para>
/// Synthesizes a dedicated <see cref="ViewModel"/> matching the prefab's declared bindings via <see cref="ViewModelSynthesizer"/>,
/// then loads three parallel movies using <see cref="GauntletMovie.Load"/>: an interpreted XML movie, a compiled prefab movie,
/// and a second XML movie serving as a baseline control. Applies identical mutations across all three graphs, verifying that widget trees,
/// ViewModel call logs, and assertion diagnostics match between the compiled engine and the XML baseline while filtering out baseline variance.
/// </para>
/// <para>
/// Drives verification through standard lifecycle stages: movie initialization, scalar property mutations across multiple passes,
/// child ViewModel replacements, list modifications (insertions, deletions, and clear operations), widget command invocations with diverse parameter types,
/// and movie release teardown to verify subscriber detachment parity.
/// </para>
/// </summary>
public sealed class BindingLoaderOracle
{
    private const string Namespace = "Bannerlord.UIExtenderEx.AutoGenerated.BindingOracle";
    private const int MaxDifferences = 200;
    private const int MaxDetailedChecks = 8;

    private static int _prefabs;

    private readonly WidgetFactory _widgetFactory;
    private readonly SpriteData _spriteData;
    private readonly BrushFactory _brushFactory;
    private readonly Func<UIContext> _newContext;
    private UIContext _context;
    private readonly List<string> _references;
    private readonly string _workDirectory;
    private readonly OracleCompiler _compiler = new();
    private readonly bool _objectTyped;

    /// <param name="objectTyped">Configures synthesized ViewModels to declare loosely typed <see cref="object"/> properties to test fallback reflection paths.</param>
    public BindingLoaderOracle(WidgetFactory widgetFactory, SpriteData spriteData, BrushFactory brushFactory, UIContext context, IEnumerable<Assembly> widgetAssemblies, bool objectTyped = false)
        : this(widgetFactory, spriteData, brushFactory, () => context, widgetAssemblies, objectTyped) { }

    /// <param name="newContext">
    /// Supplies a distinct <see cref="UIContext"/> per prefab evaluation, isolating event manager registrations across test runs.
    /// </param>
    /// <param name="objectTyped">Configures synthesized ViewModels to declare loosely typed <see cref="object"/> properties to test fallback reflection paths.</param>
    public BindingLoaderOracle(WidgetFactory widgetFactory, SpriteData spriteData, BrushFactory brushFactory, Func<UIContext> newContext, IEnumerable<Assembly> widgetAssemblies, bool objectTyped = false)
    {
        _objectTyped = objectTyped;
        _widgetFactory = widgetFactory;
        _spriteData = spriteData;
        _brushFactory = brushFactory;
        _newContext = () => WithTheLayersNavigation(newContext());
        _context = _newContext();
        var seeds = new HashSet<Assembly>(widgetAssemblies)
        {
            typeof(ViewModel).Assembly, typeof(Widget).Assembly, typeof(WidgetPrefab).Assembly, typeof(SpriteData).Assembly,
            typeof(PrefabReferenceSet).Assembly, typeof(GauntletMovie).Assembly, typeof(DynamicMember).Assembly, typeof(SynthValues).Assembly,
        };
        _references = PrefabReferenceSet.ToPaths(PrefabReferenceSet.Select(seeds));
        _workDirectory = Path.Combine(Path.GetTempPath(), "UIExtenderEx-oracle", "viewmodels-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_workDirectory);
        // Initializes gamepad navigation manager to prevent null-reference exceptions in EventManager when detaching widgets.
        TaleWorlds.GauntletUI.GamepadNavigation.GauntletGamepadNavigationManager.Initialize();
        // Resolves dynamically compiled ViewModel assemblies when compiled prefabs bind type references by name.
        AppDomain.CurrentDomain.AssemblyResolve += (_, args) =>
            _compiler.Assemblies.FirstOrDefault(x => string.Equals(x.FullName, args.Name, StringComparison.Ordinal));
    }

    /// <summary>
    /// Configures the <see cref="UIContext"/> with an active navigation context to ensure gamepad scopes unsubscribe correctly when widgets detach.
    /// </summary>
    private static UIContext WithTheLayersNavigation(UIContext context)
    {
        if (context.GamepadNavigation is EmptyGamepadNavigationContext)
            context.InitializeGamepadNavigation(new GauntletGamepadNavigationContext(_ => false, () => 0, () => true));
        return context;
    }

    /// <summary>
    /// Finalizes the current context and advances to a fresh <see cref="UIContext"/> instance for the next prefab execution.
    /// </summary>
    private void NextContext()
    {
        var next = _newContext();
        if (!ReferenceEquals(next, _context))
            _context.OnFinalize();
        _context = next;
    }

    private sealed class Case
    {
        public Case(string prefab) => Prefab = prefab;

        public string Prefab { get; }
        public string Namespace { get; } = $"{BindingLoaderOracle.Namespace}.P{System.Threading.Interlocked.Increment(ref _prefabs)}";
        public ViewModelSynthesizer? Synthesizer { get; set; }
        public string? ViewModelSource { get; set; }
        public Type? ViewModelType { get; set; }
        public List<GeneratedSource> PrefabSources { get; } = [];
        public Assembly? PrefabAssembly { get; set; }
    }

    /// <summary>
    /// Validates and serves dynamically compiled prefab variants belonging exclusively to the oracle's test namespace.
    /// </summary>
    private sealed class OracleRuntime : Bannerlord.UIExtenderEx.Runtimes.IPrefabRuntime
    {
        public static readonly OracleRuntime Instance = new();

        public bool TryServe(WidgetFactory widgetFactory, string movieName, IViewModel? dataSource) =>
            dataSource?.GetType().Namespace?.StartsWith(Namespace, StringComparison.Ordinal) == true;

        public bool IsOwnVariant(Assembly variantAssembly) => variantAssembly.GetName().Name?.StartsWith(Namespace, StringComparison.Ordinal) == true;
    }

    public List<OracleResult> Run(IReadOnlyList<string> prefabNames, int batchSize = 24)
    {
        Bannerlord.UIExtenderEx.Runtimes.PrefabRuntimes.Register(OracleRuntime.Instance);
        var previousHost = DynamicMember.Host;
        // Installs the runtime member accessor host to resolve fast reflection dispatches during evaluation.
        DynamicMember.Host = new DynamicMemberHost();
        try
        {
            var results = new List<OracleResult>();
            for (var start = 0; start < prefabNames.Count; start += batchSize)
            {
                var stopwatch = System.Diagnostics.Stopwatch.StartNew();
                results.AddRange(RunBatch([.. prefabNames.Skip(start).Take(batchSize)]));
                NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle: {Math.Min(start + batchSize, prefabNames.Count)}/{prefabNames.Count} in {stopwatch.Elapsed.TotalSeconds:F1} s");
            }
            if (MemoryLog)
                LogRetention();
            return results;
        }
        finally
        {
            DynamicMember.Host = previousHost;
        }
    }

    private static readonly bool MemoryLog = Environment.GetEnvironmentVariable("UIEXTENDEREX_ORACLE_MEMORY") == "1";

    /// <summary>
    /// Emits memory diagnostics and loaded assembly statistics when <c>UIEXTENDEREX_ORACLE_MEMORY=1</c> is configured.
    /// </summary>
    private static void LogMemory(string where)
    {
        if (!MemoryLog)
            return;
        var live = GC.GetTotalMemory(forceFullCollection: true) / (1024 * 1024);
        using var process = System.Diagnostics.Process.GetCurrentProcess();
        NUnit.Framework.TestContext.Progress.WriteLine(
            $"binding oracle memory {where}: live {live} MB, private {process.PrivateMemorySize64 / (1024 * 1024)} MB, " +
            $"working set {process.WorkingSet64 / (1024 * 1024)} MB, peak {process.PeakWorkingSet64 / (1024 * 1024)} MB, " +
            $"{AppDomain.CurrentDomain.GetAssemblies().Length} assemblies ({AppDomain.CurrentDomain.GetAssemblies().Count(x => x.IsDynamic || string.IsNullOrEmpty(x.Location))} without a file); " +
            $"still alive: {StillAlive()}");
    }

    private List<OracleResult> RunBatch(IReadOnlyList<string> prefabNames)
    {
        LogMemory("before the batch");
        var results = new List<OracleResult>();

        // 1. Synthesizes a ViewModel per prefab into a shared assembly for subsequent prefab compilation.
        var cases = new List<Case>();
        foreach (var prefab in prefabNames)
        {
            OracleMemoryGuard.Check($"synthesizing a ViewModel for '{prefab}'");
            var item = new Case(prefab);
            try
            {
                item.Synthesizer = new ViewModelSynthesizer(_widgetFactory, _objectTyped);
                item.Synthesizer.Collect(prefab);
                item.ViewModelSource = item.Synthesizer.Emit(item.Namespace);
                cases.Add(item);
            }
            catch (Exception e)
            {
                results.Add(new(prefab, OracleOutcome.XmlThrows, [], "the prefab cannot be read: " + LoaderOracle.Describe(e), 0, 0));
            }
        }

        var withViewModels = new List<Case>();
        foreach (var (group, assembly, errors) in _compiler.Compile($"{Namespace}.ViewModels", cases,
                     x => [new GeneratedSource(x.Namespace + ".ViewModels.cs", x.ViewModelSource!)], _references, SaveAndLoad))
        {
            foreach (var item in group)
            {
                if (assembly?.GetType($"{item.Namespace}.S0") is { } type)
                {
                    item.ViewModelType = type;
                    withViewModels.Add(item);
                }
                else
                {
                    results.Add(new(item.Prefab, OracleOutcome.HarnessFailed, [], "synthesized ViewModel: " + string.Join(" | ", errors.Take(3)), 0, 0));
                }
            }
        }
        LogMemory("after the ViewModels compiled");
        var references = _references.Concat(_compiler.Assemblies.Where(x => !string.IsNullOrEmpty(x.Location)).Select(x => x.Location)).Distinct().ToList();

        // 2. Generates C# code for each prefab against the synthesized ViewModels in bounded compilation batches.
        var generated = new List<Case>();
        long generatedSize = 0;
        foreach (var item in withViewModels)
        {
            try
            {
                using var lease = WidgetFactoryLookup.PrefabLease.Begin(_widgetFactory);
                var context = new PrefabCodeGenerator(item.Namespace, _widgetFactory, _spriteData, _brushFactory);
                context.AddMovie(item.Prefab, item.ViewModelType!.FullName, item.ViewModelType);
                item.PrefabSources.AddRange(context.GenerateInMemory().Select(x => new GeneratedSource(item.Namespace + "." + x.Key, x.Value)));
                if (Environment.GetEnvironmentVariable("UIEXTENDEREX_ORACLE_DUMP_SOURCES") == "1")
                {
                    var directory = Path.Combine(_workDirectory, item.Prefab);
                    Directory.CreateDirectory(directory);
                    File.WriteAllText(Path.Combine(directory, "ViewModels.cs"), item.ViewModelSource);
                    foreach (var source in item.PrefabSources)
                        File.WriteAllText(Path.Combine(directory, source.FileName), source.Content);
                    NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle: {item.Prefab} sources in {directory}");
                }
                var size = item.PrefabSources.Sum(x => (long) x.Content.Length);
                if (MemoryLog)
                    NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle source {item.Prefab}: {size / 1024} KB in {item.PrefabSources.Count} files");
                generated.Add(item);
                generatedSize += size;
            }
            catch (Exception e)
            {
                // Verifies whether interpreted XML execution succeeds to distinguish generator defects from inherent prefab defects.
                results.Add(OracleDeclines.Classify(item.Prefab, e, () => OpenFromXml(item)));
            }
            if (generatedSize >= MaxCompiledSource)
            {
                CompileAndDrive(generated, references, results);
                generated.Clear();
                generatedSize = 0;
            }
        }
        CompileAndDrive(generated, references, results);
        return results;
    }

    /// <summary>
    /// Defines the character limit for batched prefab source code compilations to constrain Roslyn memory consumption.
    /// </summary>
    private const long MaxCompiledSource = 16 * 1024 * 1024;

    /// <summary>Compiles prefab source batches, registers factory creators with <see cref="GeneratedPrefabContext"/>, and drives verification.</summary>
    private void CompileAndDrive(List<Case> generated, List<string> references, List<OracleResult> results)
    {
        if (generated.Count == 0)
            return;
        LogMemory("after the prefabs generated");
        foreach (var (group, assembly, errors) in _compiler.Compile($"{Namespace}.Prefabs", generated, x => x.PrefabSources, references))
        {
            if (assembly is null)
            {
                results.AddRange(group.Select(x => new OracleResult(x.Prefab, OracleOutcome.NotCompiled, [], string.Join(Environment.NewLine, errors.Take(5)), 0, 0)));
                continue;
            }
            LogMemory("after the prefabs compiled");
            // Registers generated widget classes with WidgetInfo using creator instances bound to the target assembly namespace.
            _compiler.Environment.CreateCreator(assembly);
            foreach (var item in group)
            {
                OracleMemoryGuard.Check($"driving '{item.Prefab}'");
                NextContext();
                item.PrefabAssembly = assembly;
                var creatorType = assembly.GetType($"{item.Namespace}.{PrefabCodeGenerator.CreatorClassName}", throwOnError: true)!;
                var collect = creatorType.GetMethod(PrefabCodeGenerator.CollectMethodName, [typeof(GeneratedPrefabContext)])!;
                collect.Invoke(Activator.CreateInstance(creatorType), [_widgetFactory.GeneratedPrefabContext]);
                var watch = System.Diagnostics.Stopwatch.StartNew();
                var driven = Drive(item);
                results.Add(driven);
                NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle: {item.Prefab} {driven.Outcome} in {watch.Elapsed.TotalSeconds:F1} s");
                LogMemory($"after {item.Prefab}");
                CollectAfterLargePrefab();
            }
        }
        // Releases generated source buffers after driving verification to free managed memory.
        foreach (var item in generated)
            item.PrefabSources.Clear();
    }

    /// <summary>Tracks the retained managed heap byte count following the most recent garbage collection cycle.</summary>
    private long _heldAfterCollect;

    private const long CollectAfterGrowth = 256 * 1024 * 1024;

    /// <summary>
    /// Triggers garbage collection when heap growth exceeds <see cref="CollectAfterGrowth"/> to stabilize memory between heavy prefabs.
    /// </summary>
    private void CollectAfterLargePrefab()
    {
        if (GC.GetTotalMemory(forceFullCollection: false) - _heldAfterCollect < CollectAfterGrowth)
            return;
        var watch = System.Diagnostics.Stopwatch.StartNew();
        GC.Collect();
        GC.WaitForPendingFinalizers();
        GC.Collect();
        _heldAfterCollect = GC.GetTotalMemory(forceFullCollection: false);
        NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle: collected in {watch.Elapsed.TotalMilliseconds:F0} ms, {_heldAfterCollect / (1024 * 1024)} MB held");
    }

    /// <summary>Attempts to load and release the movie using the interpreted XML engine, returning diagnostic error details if loading fails.</summary>
    private string? OpenFromXml(Case item)
    {
        var dataSource = (ViewModel) Activator.CreateInstance(item.ViewModelType!, new SynthValues.Log(), "Root", 1)!;
        IGauntletMovie? movie = null;
        try
        {
            movie = GauntletMovie.Load(_context, _widgetFactory, item.Prefab, dataSource, doNotUseGeneratedPrefabs: true, hotReloadEnabled: false);
            return null;
        }
        catch (Exception e)
        {
            return LoaderOracle.Describe(e);
        }
        finally
        {
            try
            {
                if (movie is { IsReleased: false })
                    movie.Release();
            }
            catch (Exception) { /* Suppresses teardown failures during test diagnostic classification. */ }
        }
    }

    private Assembly SaveAndLoad(byte[] image, string name)
    {
        var path = Path.Combine(_workDirectory, name + ".dll");
        File.WriteAllBytes(path, image);
        return Assembly.LoadFrom(path);
    }

