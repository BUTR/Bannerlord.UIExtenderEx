    /// <summary>
    /// The XML widgets left on an item a list no longer has there: <see cref="IntendedDeviations"/>' "indexed item followed".
    /// A view whose own DataSource steps into a list by index, holding another data source than its path leads to now -
    /// by XML's own measure, so nothing compiled decides it. A list item's view is not one: its path is its index alone,
    /// which XML keeps current.
    /// </summary>
    private static List<Widget> StaleIndexedInXml(Run3 run)
    {
        var stale = new List<Widget>();
        if (run.Movies[0] is not GauntletMovie movie || ChildrenOfView is null || OwnPathOfView is null || MovieViewModelAtPath is null)
            return stale;
        var pending = new Stack<GauntletView>();
        pending.Push(movie.RootView);
        while (pending.Count > 0)
        {
            var view = pending.Pop();
            if (OwnPathOfView.GetValue(view) is BindingPath { Nodes.Length: > 1 } own && own.Nodes.Any(x => x.Length > 0 && char.IsDigit(x[0])))
            {
                var held = ViewModelOfView?.GetValue(view) ?? BindingListOfView?.GetValue(view);
                var current = MovieViewModelAtPath.Invoke(movie, [view.ViewModelPath, view.ItemTemplateUsageWithData?.ItemTemplateUsage != null]);
                if (!ReferenceEquals(held, current))
                {
                    stale.Add(view.Target);
                    continue;
                }
            }
            foreach (GauntletView child in (IEnumerable) ChildrenOfView.GetValue(view)!)
                pending.Push(child);
        }
        return stale;
    }

    private static readonly System.Text.RegularExpressions.Regex CountValue = new(@"^count (\d+)$");

    /// <summary>
    /// Identifies tracking collection count discrepancies caused by redundant widget rebuilding in the interpreted XML engine.
    /// </summary>
    private static bool IsRebuildRecord(Run3 run, string key, string? xml, string? compiled)
    {
        var colon = key.IndexOf(':');
        if (colon < 0 || run.Movies[0]?.RootWidget is not { } xmlRoot)
            return false;
        var bracket = key.IndexOf('[', colon);
        var field = bracket < 0 ? key.Substring(colon + 1) : key.Substring(colon + 1, bracket - colon - 1);
        if (WidgetAt(xmlRoot, key.Substring(0, colon)) is not { } widget)
            return false;
        var recorded = run.RebuildRecords.TryGetValue((widget, field), out var offset);
        // Validates indexed entries belonging to collections inflated by XML widget rebuilds.
        if (bracket >= 0)
            return recorded;
        if (xml is null || compiled is null || CountValue.Match(xml) is not { Success: true } x || CountValue.Match(compiled) is not { Success: true } c)
            return false;
        var more = int.Parse(x.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture) - int.Parse(c.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture);
        if (recorded)
            return more == offset;
        if (more <= 0 || !run.RebuiltSinceCheck.Any(item => IsAbove(widget, item)))
            return false;
        run.RebuildRecords[(widget, field)] = more;
        return true;
    }

    private static bool IsAbove(Widget ancestor, Widget widget)
    {
        for (var parent = widget.ParentWidget; parent is not null; parent = parent.ParentWidget)
        {
            if (parent == ancestor)
                return true;
        }
        return false;
    }

