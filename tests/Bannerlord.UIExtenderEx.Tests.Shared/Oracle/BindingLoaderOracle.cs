    /// <summary>Holds the runtime execution state and movies for XML, compiled, and XML control instances.</summary>
    private sealed class Run3
    {
        public readonly SynthValues.Log[] Logs = [new(), new(), new()];
        public readonly ViewModel[] ViewModels = new ViewModel[3];
        public readonly IGauntletMovie?[] Movies = new IGauntletMovie?[3];
        public readonly List<string>[] Asserts = [[], [], []];
        public readonly List<string> Differences = [];
        /// <summary>Tracks reported widget hierarchy paths to ensure persistent differences are recorded only once.</summary>
        public readonly HashSet<string> Reported = new(StringComparer.Ordinal);

        /// <summary>
        /// Stores widgets that intentionally diverge due to recognized runtime design differences documented in <see cref="IntendedDeviations"/>.
        /// </summary>
        public readonly List<Widget> Diverged = [];

        /// <summary>Tracks the log read offset for each test movie to support incremental comparison across evaluation steps.</summary>
        public readonly int[] LogMarks = new int[3];
        public int ComparedAsserts;
        public int Checks;

        /// <summary>Maps ViewModel properties bound to widget properties that TaleWorlds engine resets upon widget detachment.</summary>
        public Dictionary<string, HashSet<string>> ResetOnRemoval = new(StringComparer.Ordinal);

        /// <summary>Indicates whether an intentional deviation occurred during the step, bypassing ViewModel invocation comparisons.</summary>
        public bool IntendedSinceCheck;
        public Func<string, string> CompiledAsVisible = x => x;

        /// <summary>Tracks XML widget instances rebuilt due to known interpreted runtime list reset behavior.</summary>
        public readonly List<Widget> RebuiltSinceCheck = [];

        /// <summary>
        /// Records element count offsets in widget internal tracking collections caused by redundant XML list reconstructions.
        /// </summary>
        public readonly Dictionary<(Widget Widget, string Field), int> RebuildRecords = [];

        /// <summary>Accumulates elapsed execution duration by operation category.</summary>
        public readonly Dictionary<string, TimeSpan> Spent = new(StringComparer.Ordinal);

        public T Timed<T>(string what, Func<T> action)
        {
            var watch = System.Diagnostics.Stopwatch.StartNew();
            try
            {
                return action();
            }
            finally
            {
                Spent[what] = (Spent.TryGetValue(what, out var spent) ? spent : TimeSpan.Zero) + watch.Elapsed;
            }
        }

        public void Timed(string what, Action action) => Timed<object?>(what, () =>
        {
            action();
            return null;
        });

        /// <summary>Formats elapsed durations exceeding threshold limits and resets the timing accumulators.</summary>
        public string TakeSpent()
        {
            var text = string.Join(", ", Spent.Where(x => x.Value.TotalSeconds >= 0.1).OrderByDescending(x => x.Value)
                .Select(x => $"{x.Key} {x.Value.TotalSeconds:F1}s"));
            Spent.Clear();
            return text.Length == 0 ? "" : $" ({text})";
        }
    }

    private OracleResult Drive(Case item)
    {
        var run = new Run3 { ResetOnRemoval = item.Synthesizer!.BoundToResetOnRemoval };
        if (item.PrefabAssembly is { } prefabAssembly)
            run.CompiledAsVisible = x => _compiler.AsVisible(x, prefabAssembly);
        var type = item.ViewModelType!;
        for (var side = 0; side < 3; side++)
            run.ViewModels[side] = (ViewModel) Activator.CreateInstance(type, run.Logs[side], "Root", 1)!;

        var failures = new string?[3];
        for (var side = 0; side < 3; side++)
        {
            var captured = side;
            failures[side] = Apply(run, side, () => run.Movies[captured] = GauntletMovie.Load(_context, _widgetFactory, item.Prefab, run.ViewModels[captured],
                doNotUseGeneratedPrefabs: captured != 1, hotReloadEnabled: false));
        }
        try
        {
            if (failures[0] is not null)
                return new(item.Prefab, OracleOutcome.XmlThrows, [], failures[0], run.Asserts[0].Count, 0);
            if (failures[1] is not null)
                return new(item.Prefab, OracleOutcome.CompiledThrows, [], "opening: " + failures[1], run.Asserts[0].Count, run.Asserts[1].Count);
            if (run.Movies[1] is GauntletMovie)
                return new(item.Prefab, OracleOutcome.CompiledThrows, [], "GauntletMovie.Load took the XML path: the compiled variant was not found", 0, 0);

            if (Environment.GetEnvironmentVariable("UIEXTENDEREX_ORACLE_DUMP_VIEWS") == "1" && run.Movies[0] is GauntletMovie xmlMovie)
                NUnit.Framework.TestContext.Progress.WriteLine(DumpViews(xmlMovie.RootView, 0));
            var phases = new System.Text.StringBuilder();
            var watch = System.Diagnostics.Stopwatch.StartNew();
            void Phase(string name, Action action)
            {
                var checks = run.Checks;
                OracleMemoryGuard.At($"'{item.Prefab}', {name}");
                LogMemory($"'{item.Prefab}' before {name}");
                watch.Restart();
                run.Spent.Clear();
                action();
                LogMemory($"'{item.Prefab}' after {name}");
                phases.Append($" {name} {watch.Elapsed.TotalSeconds:F1}s/{run.Checks - checks}{run.TakeSpent()}");
            }
            Phase("open", () => Check(run, "opening", deep: true));
            Phase("properties", () => ChangeProperties(run));
            Phase("children", () => ReplaceChildren(run));
            Phase("lists", () => ChangeLists(run));
            Phase("commands", () => FireCommands(run, item.Synthesizer!.EventNames));
            Phase("release", () => Release(run));
            NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle phases: {item.Prefab}:{phases}");

            var outcome = run.Differences.Count == 0 ? OracleOutcome.Match : OracleOutcome.Differs;
            return new(item.Prefab, outcome, [.. run.Differences.Take(MaxDifferences)], null, run.Asserts[0].Count, run.Asserts[1].Count);
        }
        catch (Exception e)
        {
            return new(item.Prefab, OracleOutcome.CompiledThrows, [.. run.Differences.Take(MaxDifferences)], "driving: " + LoaderOracle.Describe(e), run.Asserts[0].Count, run.Asserts[1].Count);
        }
        finally
        {
            foreach (var movie in run.Movies)
            {
                try
                {
                    if (movie is { IsReleased: false })
                        movie.Release();
                }
                catch (Exception) { /* Suppresses release teardown exceptions during final disposal. */ }
            }
            if (MemoryLog)
                Track(item.Prefab, run);
        }
    }

    private static readonly List<(string Prefab, string What, WeakReference Target)> Tracked = [];

    /// <summary>Maintains weak references to completed movie instances and widgets to monitor memory reclamation.</summary>
    private static void Track(string prefab, Run3 run)
    {
        for (var side = 0; side < 3; side++)
        {
            if (run.Movies[side]?.RootWidget is { } root)
                Tracked.Add((prefab, SideNames[side] + " tree", new WeakReference(root)));
            if (run.Movies[side] is { } movie)
                Tracked.Add((prefab, SideNames[side] + " movie", new WeakReference(movie)));
            Tracked.Add((prefab, SideNames[side] + " ViewModel", new WeakReference(run.ViewModels[side])));
        }
        Tracked.Add((prefab, "run", new WeakReference(run)));
    }

    /// <summary>Inspects and logs GC reference retention roots for widgets remaining reachable after batch execution.</summary>
    private void LogRetention()
    {
        GC.Collect();
        GC.WaitForPendingFinalizers();
        GC.Collect();
        var first = Tracked.FirstOrDefault().Prefab;
        var assemblies = AppDomain.CurrentDomain.GetAssemblies()
            .Where(x => x.GetName().Name is { } name && (name.StartsWith("TaleWorlds.", StringComparison.Ordinal) || name.StartsWith("Bannerlord.", StringComparison.Ordinal)))
            .ToList();
        foreach (var (prefab, what, reference) in Tracked.Where(x => x.Prefab == first && x.What.EndsWith(" tree", StringComparison.Ordinal)))
        {
            if (reference.Target is not { } target)
            {
                NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle retention: {prefab} {what} was collected");
                continue;
            }
            var path = OracleRetention.PathTo(target, assemblies,
                [("the oracle's UIContext", _context), ("the oracle's WidgetFactory", _widgetFactory), ("the oracle's BrushFactory", _brushFactory), ("the oracle", this)]);
            NUnit.Framework.TestContext.Progress.WriteLine($"binding oracle retention: {prefab} {what} is held by{Environment.NewLine}    {path ?? "nothing found from the roots searched"}");
        }
    }

    private static string StillAlive()
    {
        var alive = Tracked.Where(x => x.Target.IsAlive).GroupBy(x => x.Prefab).Select(x => $"{x.Key} [{string.Join(", ", x.Select(y => y.What))}]").ToList();
        return alive.Count == 0 ? "nothing of the prefabs driven before" : string.Join("; ", alive);
    }

    private static readonly string[] SideNames = ["xml", "compiled", "control"];

    /// <summary>Executes an action on a specific movie instance, capturing thrown exceptions and diagnostic assertion messages.</summary>
    private static string? Apply(Run3 run, int side, Action action)
    {
        using (run.Timed("asserts", () => LoaderOracle.RecordAsserts(run.Asserts[side])))
        {
            try
            {
                run.Timed(SideNames[side], action);
                return null;
            }
            catch (Exception e)
            {
                // Normalizes exception details by capturing unwrapped innermost messages across XML and compiled stacks.
                var inner = e;
                while (inner is TargetInvocationException { InnerException: { } wrapped })
                    inner = wrapped;
                return $"{inner.GetType().Name}: {inner.Message}";
            }
        }
    }

    /// <summary>Applies an operation across all three movie variants, recording discrepancies when the compiled movie diverges from XML baseline parity.</summary>
    private static void ApplyToAll(Run3 run, string label, Action<int> action)
    {
        var failures = new string?[3];
        for (var side = 0; side < 3; side++)
        {
            var captured = side;
            OracleMemoryGuard.At($"{label}, {(side == 1 ? "compiled" : side == 0 ? "XML" : "the XML control")}");
            failures[side] = Apply(run, side, () => action(captured));
        }
        if (failures[0] == failures[2] && failures[0] != failures[1] && !IsParsedAlignmentName(failures[0], failures[1]) && !IsCastNumber(failures[0], failures[1])
            && !IsNeverFittingWriteBack(failures[0], failures[1]))
            Record(run, $"{label}: XML {failures[0] ?? "succeeds"}, compiled {failures[1] ?? "succeeds"}");
    }

    private static readonly System.Text.RegularExpressions.Regex ConversionRejected = new(
        @"^ArgumentException: Object of type '(?<announced>[^']+)' cannot be converted to type '(?<property>[^']+)'\.$");

    /// <summary>
    /// Determines whether an exception matches the recognized intentional deviation where compiled write-backs safely drop incompatible types.
    /// </summary>
    private static bool IsNeverFittingWriteBack(string? xml, string? compiled)
    {
        if (compiled is not null || xml is null || ConversionRejected.Match(xml) is not { Success: true } match)
            return false;
        if (FindType(match.Groups["announced"].Value) is not { } announced || FindType(match.Groups["property"].Value) is not { } property)
            return false;
        if (announced == typeof(string) || NumberRejected.IsMatch(xml))
            return false;
        return !property.IsAssignableFrom(announced) && (property.IsValueType || property.IsSealed) && !property.IsInterface;
    }

    private static readonly Dictionary<string, Type?> TypesByName = new(StringComparer.Ordinal);

    private static Type? FindType(string fullName)
    {
        lock (TypesByName)
        {
            if (!TypesByName.TryGetValue(fullName, out var type))
                TypesByName[fullName] = type = AppDomain.CurrentDomain.GetAssemblies().Select(x => x.GetType(fullName, false)).FirstOrDefault(x => x is not null);
            return type;
        }
    }

