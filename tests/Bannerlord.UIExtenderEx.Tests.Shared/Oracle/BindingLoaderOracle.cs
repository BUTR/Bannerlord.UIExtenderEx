    private static readonly FieldInfo? ViewModelOfView = typeof(GauntletView).GetField("_viewModel", BindingFlags.Instance | BindingFlags.NonPublic);

    private static Dictionary<string, (Widget Widget, object? ViewModel)> IdentitiesOf(Widget? root)
    {
        var identities = new Dictionary<string, (Widget, object?)>(StringComparer.Ordinal);
        if (root is null)
            return identities;
        var pending = new Stack<(string, Widget)>();
        pending.Push(("root", root));
        while (pending.Count > 0)
        {
            var (path, widget) = pending.Pop();
            identities[path] = (widget, widget.GetComponent<GauntletView>() is { } view ? ViewModelOfView?.GetValue(view) : null);
            for (var i = 0; i < widget.ChildCount; i++)
                pending.Push(($"{path}[{i}]", widget.GetChild(i)));
        }
        return identities;
    }

    /// <summary>
    /// Detects widgets recreated by the interpreted XML engine despite bound list data remaining unchanged.
    /// </summary>
    private static List<Widget> RebuiltInXml(Dictionary<string, (Widget Widget, object? ViewModel)>[] before, Dictionary<string, (Widget Widget, object? ViewModel)>[] after)
    {
        var rebuilt = new List<Widget>();
        // Evaluates shallowest paths first so parent rebuilds encompass descendants.
        var rebuiltPaths = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (path, xmlAfter) in after[0].OrderBy(x => x.Key.Length))
        {
            if (IsUnderAny(path, rebuiltPaths))
                continue;
            if (before[0].TryGetValue(path, out var xmlBefore) && xmlBefore.Widget != xmlAfter.Widget
                && xmlBefore.ViewModel is not null && ReferenceEquals(xmlBefore.ViewModel, xmlAfter.ViewModel)
                && before[1].TryGetValue(path, out var compiledBefore) && after[1].TryGetValue(path, out var compiledAfter)
                && compiledBefore.Widget == compiledAfter.Widget)
            {
                rebuilt.Add(xmlAfter.Widget);
                rebuiltPaths.Add(path);
            }
        }
        return rebuilt;
    }

    /// <summary>Determines whether a hierarchy path represents a descendant of any path in <paramref name="ancestors"/>.</summary>
    private static bool IsUnderAny(string path, HashSet<string> ancestors)
    {
        if (ancestors.Count == 0)
            return false;
        for (var end = path.LastIndexOf('['); end > 0; end = path.LastIndexOf('[', end - 1))
        {
            if (ancestors.Contains(path.Substring(0, end)))
                return true;
        }
        return false;
    }

    /// <summary>
    /// Determines whether replacing a child ViewModel updated the compiled widget while leaving the XML widget unchanged.
    /// </summary>
    private static bool IsStaleInXml(AgreedValues before, string path, Dictionary<string, string> xmlAfter, Dictionary<string, string> compiledAfter)
    {
        if (!before.TryGetValue(path, out var agreed))
            return false;
        foreach (var (key, was) in agreed)
        {
            if (xmlAfter.TryGetValue(key, out var xml) && HashOf(xml) == was
                && compiledAfter.TryGetValue(key, out var compiled) && HashOf(compiled) != was)
            {
                return true;
            }
        }
        return false;
    }

    /// <summary>
    /// Computes 64-bit value hashes for matching widget properties across XML and compiled trees to minimize memory footprint.
    /// </summary>
    private Dictionary<string, ulong> Agreed(Dictionary<string, string> xmlValues, Dictionary<string, string> compiledValues)
    {
        var agreed = new Dictionary<string, ulong>(StringComparer.Ordinal);
        foreach (var (key, xml) in xmlValues)
        {
            if (!WidgetSnapshot.IsField(key) && compiledValues.TryGetValue(key, out var compiled) && compiled == xml)
                agreed[Shared(key)] = HashOf(xml);
        }
        return agreed;
    }

    private readonly Dictionary<string, string> _keys = new(StringComparer.Ordinal);

    /// <summary>Interns snapshot property key strings to deduplicate allocations across widget hierarchy traversals.</summary>
    private string Shared(string key)
    {
        if (_keys.TryGetValue(key, out var shared))
            return shared;
        _keys[key] = key;
        return key;
    }

    /// <summary>Calculates a 64-bit FNV-1a hash of the specified string value.</summary>
    private static ulong HashOf(string value)
    {
        unchecked
        {
            var hash = 14695981039346656037UL;
            foreach (var c in value)
            {
                hash ^= c;
                hash *= 1099511628211UL;
            }
            return hash;
        }
    }

    /// <summary>Extracts the widget hierarchy path from a snapshot property key.</summary>
    private static string WidgetPathOf(string key)
    {
        var end = key.IndexOfAny(['.', ':']);
        return end < 0 ? key : key.Substring(0, end);
    }

    /// <summary>Determines whether a property key corresponds to an intentionally diverged widget or descendant.</summary>
    private static bool IsDiverged(string key, List<string> divergedPaths)
    {
        var widget = WidgetPathOf(key);
        return divergedPaths.Any(x => widget.StartsWith(x, StringComparison.Ordinal) && (widget.Length == x.Length || widget[x.Length] == '['));
    }

    /// <summary>Resolves current hierarchy paths for all diverged XML widgets.</summary>
    private static List<string> DivergedPaths(Run3 run)
    {
        var paths = new List<string>();
        if (run.Movies[0]?.RootWidget is not { } root)
            return paths;
        foreach (var widget in run.Diverged)
        {
            var steps = new List<int>();
            var current = widget;
            while (current != root && current.ParentWidget is { } parent)
            {
                steps.Insert(0, parent.GetChildIndex(current));
                current = parent;
            }
            if (current == root)
                paths.Add("root" + string.Concat(steps.Select(x => $"[{x}]")));
        }
        return paths;
    }

    /// <summary>Navigates the widget hierarchy to find the widget at the specified path, returning <see langword="null"/> if not found.</summary>
    private static Widget? WidgetAt(Widget root, string path)
    {
        var current = root;
        foreach (var part in path.Substring("root".Length).Split(['['], StringSplitOptions.RemoveEmptyEntries))
        {
            var index = int.Parse(part.TrimEnd(']'), System.Globalization.CultureInfo.InvariantCulture);
            if (index >= current.ChildCount)
                return null;
            current = current.GetChild(index);
        }
        return current;
    }

    /// <summary>Captures shallow property agreement maps between XML and compiled widget hierarchies.</summary>
    private AgreedValues Shallow(Run3 run) => run.Timed("snapshots", () =>
    {
        var agreed = new AgreedValues(StringComparer.Ordinal);
        if (run.Movies[0]?.RootWidget is not { } xmlRoot || run.Movies[1]?.RootWidget is not { } compiledRoot)
            return agreed;
        var compiled = WidgetSnapshot.Take(compiledRoot, _compiler.VisibleType, 0);
        foreach (var (path, xmlValues) in WidgetSnapshot.Take(xmlRoot, _compiler.VisibleType, 0))
        {
            if (compiled.TryGetValue(path, out var compiledValues))
                agreed[path] = Agreed(xmlValues, compiledValues);
        }
        return agreed;
    });

    /// <summary>
    /// Verifies state parity across XML, compiled, and control trees, checking snapshots, ViewModel call logs, and assertions.
    /// </summary>
    /// <param name="label">The diagnostic label identifying the active evaluation step.</param>
    /// <param name="deep">Indicates whether to perform deep recursive property inspection.</param>
    /// <param name="replacingBefore">Baseline property values before child ViewModel replacement, used to detect stale bindings.</param>
    /// <param name="trees">Indicates whether to compare widget hierarchies.</param>
    /// <param name="keepShallow">Indicates whether to retain shallow snapshot agreement maps.</param>
    /// <returns>Shallow agreement maps when requested by <paramref name="keepShallow"/>; otherwise, <see langword="null"/>.</returns>
    private AgreedValues? Check(Run3 run, string label, bool deep = false, AgreedValues? replacingBefore = null, bool trees = true, bool keepShallow = false)
    {
        OracleMemoryGuard.At("checking after " + label);
        run.Checks++;
        var intended = run.IntendedSinceCheck;
        run.IntendedSinceCheck = false;

        // Captures pre- and post-replacement state directly during traversal to avoid duplicate tree scans.
        var stale = new List<string>();
        var shallow = keepShallow && !deep ? new AgreedValues(StringComparer.Ordinal) : null;
        if (keepShallow && deep)
            throw new ArgumentException("A deep comparison reads more than a shallow snapshot holds.", nameof(keepShallow));
        Action<string, Dictionary<string, string>, Dictionary<string, string>>? visit = replacingBefore is null && shallow is null ? null : (path, xmlValues, compiledValues) =>
        {
            if (replacingBefore is not null && IsStaleInXml(replacingBefore, path, xmlValues, compiledValues))
                stale.Add(path);
            // Omits paths where widgets do not exist on both sides.
            if (shallow is not null && xmlValues.Count > 0 && compiledValues.Count > 0)
                shallow[path] = Agreed(xmlValues, compiledValues);
        };

        // Compares widgets incrementally during traversal to avoid allocating massive full-tree snapshot dictionaries.
        var roots = run.Movies.Select(x => trees ? x?.RootWidget : null).ToArray();
        var differences = run.Timed(deep ? "compare deep" : "compare", () => WidgetSnapshot.Compare(roots[0], roots[1], roots[2], _compiler.VisibleType, deep ? 2 : 0, missingControlIsUnstable: true, visit));
        if (stale.Count > 0 && run.Movies[0]?.RootWidget is { } xmlRoot)
        {
            run.Diverged.AddRange(stale.Select(x => WidgetAt(xmlRoot, x)).OfType<Widget>());
            intended = true;
        }
        var divergedPaths = DivergedPaths(run);
        foreach (var (key, difference, xml, compiled) in differences)
        {
            // Skips subscriber discrepancies caused by discarded XML list items retaining ancestor subscriptions.
            if (key.EndsWith(WidgetSnapshot.RemovedSubscribers, StringComparison.Ordinal) && WidgetSnapshot.HandlerCount(xml) >= WidgetSnapshot.HandlerCount(compiled))
                continue;
            if (IsRebuildRecord(run, key, xml, compiled))
                continue;
            if (!LoaderOracle.IgnoredProperties.ContainsKey(LoaderOracle.LastSegment(key)) && !IsDiverged(key, divergedPaths) && run.Reported.Add(difference))
                Record(run, $"{label}: {difference}");
        }
        run.RebuiltSinceCheck.Clear();

        // Compares ViewModel invocation logs for the current step, skipping checks when an intentional deviation occurred.
        var steps = run.Timed("logs", () => run.Logs.Select((x, side) => x.Entries.Skip(run.LogMarks[side]).ToList()).ToArray());
        // Filters out reset write-backs emitted by XML during widget disconnection.
        if (!intended && steps[0].SequenceEqual(steps[2]) && !steps[0].SequenceEqual(steps[1])
            && steps[0].Where(x => !IsResetWrittenBack(run, x)).SequenceEqual(steps[1]))
        {
            intended = true;
        }
        if (!intended && steps[0].SequenceEqual(steps[2]))
        {
            for (var i = 0; i < Math.Max(steps[0].Count, steps[1].Count); i++)
            {
                var xmlEntry = i < steps[0].Count ? steps[0][i] : "<nothing>";
                var compiledEntry = i < steps[1].Count ? steps[1][i] : "<nothing>";
                if (xmlEntry != compiledEntry)
                {
                    if (Environment.GetEnvironmentVariable("UIEXTENDEREX_ORACLE_DUMP_LOGS") == "1")
                    {
                        NUnit.Framework.TestContext.Progress.WriteLine($"--- {label}: this step's calls from {Math.Max(0, i - 6)}");
                        foreach (var entry in steps[0].Skip(Math.Max(0, i - 6)).Take(12))
                            NUnit.Framework.TestContext.Progress.WriteLine("  X " + entry);
                        foreach (var entry in steps[1].Skip(Math.Max(0, i - 6)).Take(12))
                            NUnit.Framework.TestContext.Progress.WriteLine("  C " + entry);
                    }
                    Record(run, $"{label}: call {i} of the step: XML '{xmlEntry}', compiled '{compiledEntry}'");
                    break;
                }
            }
        }
        for (var side = 0; side < 3; side++)
            run.LogMarks[side] = run.Logs[side].Entries.Count;

        var asserts = run.Asserts.Select(x => x.Count - run.ComparedAsserts).ToArray();
        if (asserts[0] == asserts[2] && asserts[0] != asserts[1])
            Record(run, $"{label}: asserts XML {asserts[0]}, compiled {asserts[1]} [{string.Join(" | ", run.Asserts[0].Skip(run.ComparedAsserts).Take(2))}] [{string.Join(" | ", run.Asserts[1].Skip(run.ComparedAsserts).Take(2))}]");
        else if (asserts[0] == asserts[1])
        {
            // Compares assertion frequency and diagnostic message parity against the control baseline.
            var stepAsserts = run.Asserts.Select(x => x.Skip(run.ComparedAsserts).ToList()).ToArray();
            foreach (var difference in LoaderOracle.AssertDifferences(stepAsserts[0], [.. stepAsserts[1].Select(run.CompiledAsVisible)], stepAsserts[2]).Take(3))
                Record(run, $"{label}: {difference}");
        }
        // Synchronizes assertion collections across all three variants using unified padding.
        foreach (var list in run.Asserts)
        {
            if (list.Count < run.Asserts.Max(x => x.Count))
                list.AddRange(Enumerable.Repeat("<padding>", run.Asserts.Max(x => x.Count) - list.Count));
        }
        run.ComparedAsserts = run.Asserts[0].Count;
        return shallow;
    }

    /// <summary>Formats diagnostic hierarchy dumps of GauntletView instances and their bound ViewModels.</summary>
    private static string DumpViews(GauntletView view, int depth)
    {
        var flags = BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public;
        var viewModel = typeof(GauntletView).GetField("_viewModel", flags)?.GetValue(view);
        var list = typeof(GauntletView).GetField("_bindingList", flags)?.GetValue(view);
        var children = (IEnumerable) typeof(GauntletView).GetField("_children", flags)!.GetValue(view)!;
        var sb = new System.Text.StringBuilder();
        sb.AppendLine($"{new string(' ', depth * 2)}{view.Target.GetType().Name} path={view.ViewModelPathString} vm={viewModel?.GetType().Name ?? "null"} list={list?.GetType().Name ?? "null"}");
        foreach (GauntletView child in children)
            sb.Append(DumpViews(child, depth + 1));
        return sb.ToString();
    }

