    private static string FoldConstructs(string output)
    {
        foreach (var (pattern, replacement, _) in FoldedConstructs)
            output = Regex.Replace(output, pattern, replacement);
        return output;
    }

    private static string RemoveIgnoredConstructs(string output)
    {
        // Strip ignored constructs completely rather than marking, as emission locations differ across generators.
        // Verifies exact matching of all surrounding code.
        foreach (var (pattern, _) in IgnoredConstructs)
            output = Regex.Replace(output, pattern, string.Empty);
        return output;
    }

    private static string? _gameDirectory;
    private static readonly List<string> ProbeDirectories = [];
    private static bool _resolverInstalled;
    private static Harmony? _harmony;

    [OneTimeSetUp]
    public void OneTimeSetUp()
    {
        _gameDirectory = FindGameDirectory();
        if (_gameDirectory is null)
            return;

        var gameBin = Path.Combine(_gameDirectory, "bin", "Win64_Shipping_Client");
        ProbeDirectories.Add(gameBin);
        foreach (var module in new[] { "Native", "SandBoxCore", "SandBox", "StoryMode", "CustomBattle" })
        {
            var directory = Path.Combine(_gameDirectory, "Modules", module, "bin", "Win64_Shipping_Client");
            if (Directory.Exists(directory))
                ProbeDirectories.Add(directory);
        }
        if (!_resolverInstalled)
        {
            _resolverInstalled = true;
            AppDomain.CurrentDomain.AssemblyResolve += Resolve;
        }

        // Pre-load widget and ViewModel assemblies required by the generator; core assemblies load from test folder.
        foreach (var file in new[]
        {
            Path.Combine(gameBin, "TaleWorlds.GauntletUI.ExtraWidgets.dll"),
            Path.Combine(gameBin, "TaleWorlds.MountAndBlade.GauntletUI.Widgets.dll"),
            Path.Combine(gameBin, "TaleWorlds.Core.ViewModelCollection.dll"),
            Path.Combine(gameBin, "TaleWorlds.MountAndBlade.ViewModelCollection.dll"),
            Path.Combine(gameBin, "TaleWorlds.CampaignSystem.ViewModelCollection.dll"),
            Path.Combine(_gameDirectory, "Modules", "Native", "bin", "Win64_Shipping_Client", "TaleWorlds.MountAndBlade.GauntletUI.dll"),
            Path.Combine(_gameDirectory, "Modules", "SandBox", "bin", "Win64_Shipping_Client", "SandBox.GauntletUI.dll"),
            Path.Combine(_gameDirectory, "Modules", "SandBox", "bin", "Win64_Shipping_Client", "SandBox.ViewModelCollection.dll"),
        })
        {
            if (!File.Exists(file))
                continue;
            try { Assembly.LoadFrom(file).GetTypes(); }
            catch (ReflectionTypeLoadException) { /* partial load is fine */ }
        }

        // Redirect BasePath.Name to the game folder for resource resolution.
        _harmony = new Harmony(nameof(GameGeneratorEquivalenceTests));
        // Apply prefix with high priority to override competing test fixture patches.
        _harmony.Patch(SymbolExtensions2.GetPropertyGetter(() => BasePath.Name),
            prefix: new HarmonyMethod(typeof(GameGeneratorEquivalenceTests), nameof(BasePathPrefix)) { priority = Priority.First });

        Common.SetInvariantCulture();
        PrefabWorkspace.RefreshWidgetInfo();
    }

    [OneTimeTearDown]
    public void OneTimeTearDown()
    {
        _harmony?.UnpatchAll(nameof(GameGeneratorEquivalenceTests));
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    private static bool BasePathPrefix(ref string __result)
    {
        __result = _gameDirectory!.Replace('\\', '/') + "/";
        return false;
    }

    private static Assembly? Resolve(object sender, ResolveEventArgs args)
    {
        var name = new AssemblyName(args.Name).Name;
        foreach (var directory in ProbeDirectories)
        {
            var path = Path.Combine(directory, name + ".dll");
            if (File.Exists(path))
                return Assembly.LoadFrom(path);
        }
        return null;
    }

    private static string? FindGameDirectory()
    {
        var candidates = new[]
        {
            Environment.GetEnvironmentVariable("BANNERLORD_GAME_DIR"),
            Environment.GetEnvironmentVariable("BANNERLORD_STABLE_DIR"),
            @"C:\Program Files (x86)\Steam\steamapps\common\Mount & Blade II Bannerlord",
        };
        return candidates.FirstOrDefault(x =>
            !string.IsNullOrEmpty(x) &&
            File.Exists(Path.Combine(x!, "bin", "Win64_Shipping_Client", "TaleWorlds.GauntletUI.CodeGenerator.dll")) &&
            Directory.Exists(Path.Combine(x!, "Modules", "SandBox", "GUI")));
    }

    [TestCase("EscapeMenu", "TaleWorlds.MountAndBlade.ViewModelCollection.EscapeMenu.EscapeMenuVM")]
    [TestCase("RecruitmentPopup", "TaleWorlds.CampaignSystem.ViewModelCollection.GameMenu.Recruitment.RecruitmentVM")]
    public void Fork_EmitsTheSameCodeAsTheGameGenerator(string movieName, string viewModelTypeName)
    {
        if (_gameDirectory is null)
            Assert.Ignore("No game installation found; set BANNERLORD_GAME_DIR to run this test.");

        var viewModelType = AppDomain.CurrentDomain.GetAssemblies().Select(x => x.GetType(viewModelTypeName, false)).FirstOrDefault(x => x is not null);
        if (viewModelType is null)
            Assert.Ignore($"ViewModel type {viewModelTypeName} is not available in this game installation.");

        var gameGenerator = Assembly.LoadFrom(Path.Combine(_gameDirectory!, "bin", "Win64_Shipping_Client", "TaleWorlds.GauntletUI.CodeGenerator.dll"));
        var gameContextType = gameGenerator.GetType("TaleWorlds.GauntletUI.CodeGenerator.UICodeGenerationContext")!;
        var gameVariantType = gameGenerator.GetType("TaleWorlds.GauntletUI.CodeGenerator.UICodeGenerationDatabindingVariantExtension")!;

        var locations = new List<string> { "GUI/GauntletUI/" };
        foreach (var module in new[] { "Native", "SandBoxCore", "SandBox", "StoryMode", "CustomBattle" })
        {
            if (Directory.Exists(Path.Combine(_gameDirectory!, "Modules", module, "GUI")))
                locations.Add($"Modules/{module}/GUI/");
        }
        var data = new Dictionary<string, object> { { "DataSourceType", viewModelType! } };

        // Execute TaleWorlds generator targeting output directory.
        var outputFolder = "UIExtenderExEquivalence_" + movieName;
        var gameContext = Activator.CreateInstance(gameContextType, Namespace, outputFolder)!;
        Invoke(gameContext, gameContextType.GetMethod("Prepare", [typeof(IEnumerable<string>), typeof(IEnumerable<PrefabExtension>)])!, locations, new PrefabExtension[] { new PrefabDatabindingExtension() });
        Invoke(gameContext, gameContextType.GetMethod("AddPrefabVariant")!, movieName, viewModelType!.FullName, Activator.CreateInstance(gameVariantType), data);

        var temp = Path.Combine(Path.GetTempPath(), "UIExtenderEx-equivalence-" + Guid.NewGuid().ToString("N"));
        var workingDirectory = Path.Combine(temp, "a", "b", "c");
        var gameOutput = Path.Combine(temp, "Source", outputFolder);
        Directory.CreateDirectory(workingDirectory);
        Directory.CreateDirectory(gameOutput);
        var previousDirectory = Directory.GetCurrentDirectory();
        Dictionary<string, string> gameFiles;
        try
        {
            Directory.SetCurrentDirectory(workingDirectory);
            Invoke(gameContext, gameContextType.GetMethod("Generate")!);
            gameFiles = Directory.GetFiles(gameOutput, "*.cs").ToDictionary(Path.GetFileName, x => File.ReadAllText(x));
        }
        finally
        {
            Directory.SetCurrentDirectory(previousDirectory);
            try { Directory.Delete(temp, true); } catch (Exception) { /* ignore */ }
        }

        // Execute compiled prefab generator reusing loaded game resources.
        object Property(string name) => gameContextType.GetProperty(name)!.GetValue(gameContext)!;
        var forkContext = new PrefabCodeGenerator(Namespace, (WidgetFactory) Property("WidgetFactory"),
            (TaleWorlds.TwoDimension.SpriteData) Property("SpriteData"), (TaleWorlds.GauntletUI.BrushFactory) Property("BrushFactory"));
        forkContext.AddMovie(movieName, viewModelType.FullName, viewModelType);
        var forkFiles = forkContext.GenerateInMemory().ToDictionary(x => x.Key, x => x.Value);

        Assert.That(forkFiles.Keys, Is.EquivalentTo(gameFiles.Keys));
        foreach (var file in gameFiles)
        {
            var expected = FoldConstructs(RemoveIgnoredConstructs(ApplyIntendedDeviations(Normalize(file.Value))));
            var actual = FoldConstructs(RemoveIgnoredConstructs(Unroot(Normalize(forkFiles[file.Key]))));
            (expected, actual) = FoldResourceConstants(expected, actual);
            expected = DropWritebacksTheForkLeavesOut(expected, actual);
            if (expected != actual)
                Assert.Fail($"{file.Key} differs from the game's generator beyond the deviations this fork makes on purpose. {DumpForDiff(movieName, file.Key, expected, actual)}");
        }
        Assert.That(forkFiles[movieName + ".gen.cs"].Length, Is.GreaterThan(1000), "sanity: the movie produced real code");
    }

    private static string Normalize(string text) => text.Replace("\r\n", "\n").TrimEnd();

    private static readonly Regex WritebackHandler = new(
        @"\n(?<i>\t+)private void HandleWidgetPropertyChangeOf(?<widget>\w+)\(System\.String propertyName[^\n]*\)\n\k<i>\{\n(?:[^\n]*\n)*?\k<i>\}(?:\n[\t ]*(?=\n))?");

    /// <summary>
    /// Strips writeback handlers for widgets that do not raise property notifications from game generator output,
    /// matching compiled prefab generator suppression behavior.
    /// </summary>
    private static string DropWritebacksTheForkLeavesOut(string gameOutput, string forkOutput)
    {
        var fork = WritebackHandler.Matches(forkOutput).Cast<Match>().Select(x => x.Groups["widget"].Value).ToList();
        var next = 0;
        return WritebackHandler.Replace(gameOutput, match =>
        {
            if (next < fork.Count && fork[next] == match.Groups["widget"].Value)
            {
                next++;
                return match.Value;
            }
            return "";
        });
    }

    /// <summary>
    /// Strips the <c>global::</c> namespace qualification from compiled output to match unrooted game generator output.
    /// </summary>
    private static string Unroot(string forkOutput) => forkOutput.Replace("global::", string.Empty);

    /// <summary>
    /// Writes generator outputs to temporary disk files for diff inspection on test failure.
    /// </summary>
    private static string DumpForDiff(string movieName, string fileName, string expected, string actual)
    {
        try
        {
            var directory = Path.Combine(Path.GetTempPath(), "UIExtenderEx-equivalence-diff", movieName);
            Directory.CreateDirectory(directory);
            File.WriteAllText(Path.Combine(directory, "game-" + fileName), expected);
            File.WriteAllText(Path.Combine(directory, "fork-" + fileName), actual);
            return "Both outputs written to " + directory;
        }
        catch (Exception e)
        {
            return "Could not write the outputs for diffing: " + e.Message;
        }
    }

    // Unwraps TargetInvocationException to rethrow the underlying generator failure.
    private static void Invoke(object target, MethodInfo method, params object?[] arguments)
    {
        try
        {
            method.Invoke(target, arguments);
        }
        catch (TargetInvocationException e) when (e.InnerException is not null)
        {
            throw new InvalidOperationException($"{method.Name} failed: {e.InnerException}", e.InnerException);
        }
    }

