    /// <summary>
    /// Matches runtime resource constants resolving sprite or brush-layer dimensions. Replaces both runtime-resolved
    /// blocks and game generator baked constants with a normalized marker for structural comparison.
    /// </summary>
    /// <summary>Matches the resolve comment and following assignment block anchored to comment indentation.</summary>
    private static readonly Regex ForkResolvedConstant = new(
        @"//From constant (?<name>[^\n]+), resolved against the widget's own resources\n(?<i>\t*)\{\n(?<body>(?:[^\n]*\n)*?)\k<i>\}");

    /// <summary>Matches the specific assignment statement within a resolved constant block.</summary>
    private static readonly Regex ForkResolvedAssignment = new(@"(?<target>[\w.]+) = [^\n]*uiExtenderExResourceValue[^\n]*");

    private static string ResolvedConstantMarker(string name, string indent, string target) =>
        $"//Resource constant {name}\n{indent}{target} = <resolved at runtime>;";

    /// <summary>
    /// Folds runtime-resolved constants in <paramref name="forkOutput"/> and corresponding baked constants in
    /// <paramref name="gameOutput"/> into unified markers to verify property targeting equivalence.
    /// </summary>
    private static (string Game, string Fork) FoldResourceConstants(string gameOutput, string forkOutput)
    {
        var names = new List<string>();
        forkOutput = ForkResolvedConstant.Replace(forkOutput, match =>
        {
            var name = match.Groups["name"].Value;
            names.Add(name);
            return ResolvedConstantMarker(name, match.Groups["i"].Value, ForkResolvedAssignment.Match(match.Groups["body"].Value).Groups["target"].Value);
        });
        foreach (var name in names.Distinct())
        {
            var baked = new Regex(@"//From constant " + Regex.Escape(name) + @":[^\n]*\n(?<i>\t*)(?<target>[\w.]+) = [^\n]*");
            gameOutput = baked.Replace(gameOutput, m => ResolvedConstantMarker(name, m.Groups["i"].Value, m.Groups["target"].Value));
        }
        return (gameOutput, forkOutput);
    }

    private static string ApplyIntendedDeviations(string gameOutput)
    {
        foreach (var (pattern, replacement, _) in IntendedDeviations)
            gameOutput = Regex.Replace(gameOutput, pattern, replacement);
        return gameOutput;
    }

